function updateLanguageSwitcher(language) {
  const labels = { ar: "العربية", en: "English", ja: "日本語", ru: "Русский", la: "Latina" };
  const groupLabels = {
    ar: "اختر اللغة",
    en: "Choose language",
    ja: "言語を選択",
    ru: "Выберите язык",
    la: "Linguam elige"
  };
  const languageNames = {
    ar: { ar: "التبديل إلى العربية", en: "Switch to Arabic", ja: "アラビア語に切り替え", ru: "Переключить на арабский", la: "Arabicam linguam elige" },
    en: { ar: "التبديل إلى الإنجليزية", en: "Switch to English", ja: "英語に切り替え", ru: "Переключить на английский", la: "Anglicam linguam elige" },
    ja: { ar: "التبديل إلى اليابانية", en: "Switch to Japanese", ja: "日本語に切り替え", ru: "Переключить на японский", la: "Iaponicam linguam elige" },
    ru: { ar: "التبديل إلى الروسية", en: "Switch to Russian", ja: "ロシア語に切り替え", ru: "Переключить на русский", la: "Russicam linguam elige" },
    la: { ar: "التبديل إلى اللاتينية", en: "Switch to Latin", ja: "ラテン語に切り替え", ru: "Переключить на латынь", la: "Linguam Latinam elige" }
  };
  const group = document.querySelector(".language-switcher");
  if (!group) return;
  group.setAttribute("aria-label", groupLabels[language]);
  group.querySelectorAll("[data-language]").forEach((button) => {
    const target = button.dataset.language;
    button.setAttribute("aria-label", languageNames[target][language]);
    button.setAttribute("aria-pressed", String(target === language));
    button.classList.toggle("active", target === language);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const header = document.querySelector(".site-header");
  if (header) {
    const group = document.createElement("div");
    group.className = "language-switcher";
    group.setAttribute("role", "group");
    const languages = ["ar", "en", "ja", "ru", "la"];
    const labels = { ar: "العربية", en: "English", ja: "日本語", ru: "Русский", la: "Latina" };
    languages.forEach((language) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "language-toggle";
      button.dataset.language = language;
      button.textContent = labels[language];
      button.addEventListener("click", () => {
        localStorage.setItem("site-language", language);
        applyLanguage(language);
      });
      group.appendChild(button);
    });
    header.appendChild(group);
  }

  const saved = localStorage.getItem("site-language");
  const initial = ["ar", "en", "ja", "ru", "la"].includes(saved) ? saved : "ar";
  applyLanguage(initial);
});
