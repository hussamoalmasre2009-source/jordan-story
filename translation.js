const reverseLanguageTranslations = Object.fromEntries(
  Object.entries(languageDictionaries).map(([language, dictionary]) => [
    language,
    Object.fromEntries(Object.entries(dictionary).map(([arabic, translated]) => [translated, arabic]))
  ])
);

function translateNodeText(node, language) {
  const original = node.textContent.trim();
  if (!original) return;
  const arabic = reverseTranslations[original] || reverseJapaneseTranslations[original]
    || reverseLanguageTranslations.ru[original] || reverseLanguageTranslations.la[original] || original;
  const translated = language === "ar" ? arabic : (languageDictionaries[language]?.[arabic] || translations[arabic]);
  if (translated) node.textContent = node.textContent.replace(original, translated);
}

