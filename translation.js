const reverseTranslations = Object.fromEntries(
  Object.entries(translations).map(([arabic, english]) => [english, arabic])
);

function translateNodeText(node, language) {
  const original = node.textContent.trim();
  if (!original) return;
  if (language === "en") {
    if (translations[original]) node.textContent = node.textContent.replace(original, translations[original]);
  } else if (reverseTranslations[original]) {
    node.textContent = node.textContent.replace(original, reverseTranslations[original]);
  }
}

if (/^https?:$/.test(location.protocol)) {
  const canonical = document.querySelector("link[rel='canonical']");
  if (!canonical) {
    const link = document.createElement("link");
    link.rel = "canonical";
    const path = location.pathname.replace(/\\/g, "/");
    link.href = location.origin + (path.endsWith("/hussam.html") || path.endsWith("/index.html") ? "/jordan-story/" : path);
    document.head.appendChild(link);
  }
}

function applyLanguage(language) {
  document.documentElement.lang = language === "en" ? "en" : "ar";
  document.documentElement.dir = language === "en" ? "ltr" : "rtl";
  document.documentElement.dataset.language = language;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  textNodes.forEach((node) => translateNodeText(node, language));

  document.querySelectorAll("[alt]").forEach((element) => {
    const original = element.getAttribute("alt");
    if (language === "en" && translations[original]) element.setAttribute("alt", translations[original]);
    else if (language === "ar" && reverseTranslations[original]) element.setAttribute("alt", reverseTranslations[original]);
  });
  document.querySelectorAll("[placeholder]").forEach((element) => {
    const original = element.getAttribute("placeholder");
    if (language === "en" && translations[original]) element.setAttribute("placeholder", translations[original]);
    else if (language === "ar" && reverseTranslations[original]) element.setAttribute("placeholder", reverseTranslations[original]);
  });

  const title = document.querySelector("title");
  if (title) {
    if (language === "en") {
      if (title.textContent.includes("الثقافة")) title.textContent = "Culture & Life | Jordan";
      else if (title.textContent.includes("البتراء")) title.textContent = "Petra | Jordan";
      else if (title.textContent.includes("الطبيعة")) title.textContent = "Nature | Jordan";
      else if (title.textContent.includes("خريطة")) title.textContent = "Jordan Map and Directions";
      else title.textContent = "Jordan | The Story of a Land";
    } else {
      if (location.pathname.endsWith("culture.html")) title.textContent = "الثقافة والحياة | الأردن";
      else if (location.pathname.endsWith("petra.html")) title.textContent = "البتراء | الأردن";
      else if (location.pathname.endsWith("nature.html")) title.textContent = "الطبيعة | الأردن";
      else if (location.pathname.endsWith("map.html")) title.textContent = "خريطة الأردن والاتجاهات";
      else title.textContent = "الأردن | حكاية أرض";
    }
  }

  document.querySelectorAll(".language-toggle").forEach((button) => {
    button.textContent = language === "en" ? "العربية" : "English";
    button.setAttribute("aria-label", language === "en" ? "التبديل إلى العربية" : "Switch to English");
  });

  document.dispatchEvent(new CustomEvent("languagechange", { detail: { language } }));
}

document.addEventListener("DOMContentLoaded", () => {
  const header = document.querySelector(".site-header");
  if (header) {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "language-toggle";
    header.appendChild(button);
    button.addEventListener("click", () => {
      const next = document.documentElement.dataset.language === "en" ? "ar" : "en";
      localStorage.setItem("site-language", next);
      applyLanguage(next);
    });
  }

  const saved = localStorage.getItem("site-language");
  const initial = saved === "en" ? "en" : "ar";
  applyLanguage(initial);
});
